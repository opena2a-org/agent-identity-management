echo "============================================"
if $DRY_RUN; then
  echo "  Sync Preview (DRY RUN)"
else
  echo "  Syncing agent-identity-management -> aim-cloud"
fi
echo "============================================"
echo "  Source: $SOURCE"
echo "  Target: $TARGET"
echo "  Protected patterns: ${#PROTECTED_PATTERNS[@]}"
echo "============================================"
echo ""

sync_backend
rewrite_imports
sync_frontend
sync_migrations
sync_sdk
reconcile_go_deps
verify_build

echo ""
echo "============================================"
echo "  Sync Summary"
echo "============================================"
echo "  Files added:     $ADDED"
echo "  Files modified:  $MODIFIED"
echo "  Files skipped:   $SKIPPED"
echo "  Import rewrites: $IMPORT_REWRITES"
if $DRY_RUN; then
  echo "  Mode: DRY RUN (no files changed)"
fi
echo "============================================"
echo ""
